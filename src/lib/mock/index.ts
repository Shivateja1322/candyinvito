function buildTimeline(base: number): AnalyticsSummary["timeline"] {
  return Array.from({ length: 14 }, (_, i) => {
    const date = new Date(Date.UTC(2026, 7, i + 1));
    const wave = Math.sin(i / 2.2) * 0.35 + 1;
    return {
      date: date.toISOString().slice(0, 10),
      views: Math.round(base * wave),
      visitors: Math.round(base * wave * 0.62),
      rsvps: Math.max(0, Math.round(base * wave * 0.05)),
    };
  });
}

